const assert=require('node:assert/strict');
const fs=require('node:fs');
require('../evidence-viewer.js');
const {parseCSV,records,percentage,markup}=require('../purpose-dashboard.js');
assert.deepEqual(parseCSV('a,b\r\n"a, b","line 1\nline 2 ""quoted"""\r\n'),[['a','b'],['a, b','line 1\nline 2 "quoted"']]);
assert.throws(()=>parseCSV('"unfinished'));
for(const value of ['',null,undefined,'abc','101','-1'])assert.equal(percentage(value),null);
assert.equal(percentage('0'),0);assert.equal(percentage('50%'),50);assert.equal(percentage('100'),100);
assert.throws(()=>records([['wrong'],['headers']]));
const snapshot=JSON.parse(fs.readFileSync('data/learning-purpose.json','utf8'));
const data=records([snapshot.headers,...snapshot.rows]);
const html=markup(data,'current');
assert.equal((html.match(/<article /g)||[]).length,5);
assert.equal((html.match(/role="progressbar"/g)||[]).length,0);
assert.ok(html.includes('Awaiting Evidence'));
assert.ok(html.includes('100% commitment'));
const extra={type:'kpi',id:'later',reporting_window:'future',title:'Future-only KPI',percent:'0',sort_order:'5'};
assert.ok(!markup([...data,extra],'current').includes('Future-only KPI'));
assert.ok(markup([...data,extra],'future').includes('aria-valuenow="0"'));
const malicious=data.map(row=>row.type==='page'?{...row,title:'<img src=x onerror=alert(1)>'}:row);
assert.ok(!markup(malicious,'current').includes('<img src=x'));
assert.ok(markup(malicious,'current').includes('&lt;img'));
console.log('Purpose data checks passed: CSV, missing/zero/invalid ratings, window filtering, and escaped sheet content.');
